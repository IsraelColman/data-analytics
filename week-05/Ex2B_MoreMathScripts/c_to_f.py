# convert celsius to fahrenheit
celsius_temparature = int(input("What is the temparature in celsius?: "))

fahrenheit_temperature = (celsius_temparature * 9/5) + 32

print(f'the temparature in celsius is {celsius_temparature} degrees, and the temparature in fahrenheit is {fahrenheit_temperature:.2f} degrees.')