# convert fahrenheit to celsius
fahrenheit_temparature = int(input("What is the temparature in fahrenheit?: "))

celsius_temperature = (fahrenheit_temparature - 32) * 5/9

print(f'The temparature in fahrenheit is {fahrenheit_temparature} degrees, and the temparature in celsius is {celsius_temperature:.2f} degrees.')